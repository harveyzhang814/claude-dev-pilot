#!/usr/bin/env python3
"""
analyze.py — Process hook event JSONL files into a state feature table.

Usage:
    cd scripts/experiments
    python3 analyze.py data/raw/01_*.jsonl data/raw/02_*.jsonl data/feature_table.md

Or with a single file:
    python3 analyze.py data/fixtures/real_178_events.jsonl data/feature_table.md
"""
import json
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional


@dataclass
class HookEvent:
    hook_event_name: str
    tool_name: str = ""
    notification_type: str = ""
    session_id: str = ""
    captured_at: str = ""
    permission_mode: str = ""
    stop_hook_active: Optional[bool] = None
    raw: dict = field(default_factory=dict)


def parse_jsonl(path: str) -> list[dict]:
    """Read a JSONL file, skip blank lines and malformed JSON."""
    events = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return events


def to_hook_event(d: dict) -> Optional[HookEvent]:
    """Convert a raw dict to HookEvent. Returns None for marker events."""
    if "_marker" in d:
        return None
    hook = d.get("hook_event_name", "")
    if not hook:
        return None
    return HookEvent(
        hook_event_name=hook,
        tool_name=d.get("tool_name", ""),
        notification_type=d.get("notification_type", ""),
        session_id=d.get("session_id", ""),
        captured_at=d.get("_captured_at", ""),
        permission_mode=d.get("permission_mode", ""),
        stop_hook_active=d.get("stop_hook_active"),
        raw=d,
    )


def extract_sequences(events: list[dict]) -> dict[str, list[HookEvent]]:
    """
    Group events by session_id and sort by _captured_at timestamp.
    Events without session_id are discarded (can't be attributed).
    """
    by_session: dict[str, list[HookEvent]] = defaultdict(list)
    for d in events:
        evt = to_hook_event(d)
        if evt and evt.session_id:
            by_session[evt.session_id].append(evt)

    for sid in by_session:
        by_session[sid].sort(key=lambda e: e.captured_at)

    return dict(by_session)


def infer_state(evt: HookEvent, prior: list[HookEvent]) -> Optional[str]:
    """
    Infer the state this event implies, given the prior event context.
    Returns one of: "idle", "busy", "waiting", "completed", or None.
    """
    hook = evt.hook_event_name

    if hook == "SessionStart":
        return "idle"
    if hook == "SessionEnd":
        return "completed"
    if hook == "UserPromptSubmit":
        return "busy"
    if hook == "PreToolUse":
        return "busy"
    if hook == "PostToolUse":
        if evt.tool_name == "AskUserQuestion":
            return "busy"
        return None
    if hook == "Notification":
        if evt.notification_type == "idle_prompt":
            return "idle"
        if evt.notification_type == "permission_prompt":
            return "waiting"
        return None
    if hook == "Stop":
        recent_permission = any(
            p.hook_event_name == "Notification"
            and p.notification_type == "permission_prompt"
            for p in prior[-5:]
        )
        return "waiting" if recent_permission else "idle"

    return None


def analyze_state_transitions(sessions: dict[str, list[HookEvent]]) -> list[dict]:
    """
    For each event in each session, annotate with inferred state.
    Returns records for events where a state can be inferred.
    """
    records = []
    for sid, events in sessions.items():
        for i, evt in enumerate(events):
            state = infer_state(evt, events[:i])
            if state is not None:
                records.append({
                    "session_id": sid,
                    "hook_event_name": evt.hook_event_name,
                    "tool_name": evt.tool_name,
                    "notification_type": evt.notification_type,
                    "inferred_state": state,
                    "captured_at": evt.captured_at,
                })
    return records


def generate_feature_table(records: list[dict]) -> str:
    """Generate a markdown table mapping hook features → inferred state."""
    key_to_states: dict[tuple, Counter] = defaultdict(Counter)
    for r in records:
        key = (r["hook_event_name"], r["tool_name"], r["notification_type"])
        key_to_states[key][r["inferred_state"]] += 1

    lines = [
        "# Hook Feature Table",
        "",
        "Generated by `analyze.py` from experiment data.",
        "Use this table to define `evaluateStream()` conditions in HookStreamBuffer.",
        "",
        "| Hook | tool_name | notification_type | Inferred State | Count |",
        "|------|-----------|-------------------|----------------|-------|",
    ]

    sorted_keys = sorted(
        key_to_states.items(),
        key=lambda kv: sum(kv[1].values()),
        reverse=True,
    )

    for (hook, tool, nt), states in sorted_keys:
        for state, count in states.most_common():
            lines.append(
                f"| {hook} | {tool or '—'} | {nt or '—'} | **{state}** | {count} |"
            )

    return "\n".join(lines)


def main(input_paths: list[str], output_path: str):
    all_events: list[dict] = []
    for p in input_paths:
        events = parse_jsonl(p)
        print(f"  {p}: {len(events)} events")
        all_events.extend(events)

    print(f"\nTotal events loaded: {len(all_events)}")

    sessions = extract_sequences(all_events)
    print(f"Sessions found: {len(sessions)}")
    for sid, evts in sorted(sessions.items()):
        print(f"  {sid[:16]}: {len(evts)} events")

    records = analyze_state_transitions(sessions)
    print(f"\nAnnotated events: {len(records)}")

    table = generate_feature_table(records)

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text(table)
    print(f"\nFeature table written to: {output_path}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python3 analyze.py <input1.jsonl> [input2.jsonl ...] <output.md>")
        sys.exit(1)
    inputs = sys.argv[1:-1] if len(sys.argv) > 2 else [sys.argv[1]]
    output = sys.argv[-1] if len(sys.argv) > 2 else "data/feature_table.md"
    main(inputs, output)
